def main():
    existing_ids = set()
    if CASES_PATH.exists():
        with CASES_PATH.open("r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                existing_ids.add(json.loads(line)["id"])

    new_ids = [c["id"] for c in NEW_CASES]
    conflict = set(new_ids) & existing_ids
    if conflict:
        raise RuntimeError(f"ID conflict with existing: {sorted(conflict)}")

    with CASES_PATH.open("a", encoding="utf-8") as f:
        for c in NEW_CASES:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")
    print(f"Appended {len(NEW_CASES)} cases ({new_ids[0]} ~ {new_ids[-1]})")


if __name__ == "__main__":
    main()